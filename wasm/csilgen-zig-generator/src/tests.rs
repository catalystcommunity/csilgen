#[test]
fn server_emits_handlers_wire_ids_and_compact_router() {
    let svc = service_rule(
        "ChatService",
        vec![
            op(
                "say",
                CsilTypeExpression::Reference("SayMessage".to_string()),
                builtin("nil"),
                CsilServiceDirection::Bidirectional,
                Some(0),
            ),
            op(
                "ping",
                builtin("nil"),
                CsilTypeExpression::Reference("Pong".to_string()),
                CsilServiceDirection::Unidirectional,
                Some(1),
            ),
        ],
        Some(7),
    );
    let input = input_with_rules(vec![svc], "zig", HashMap::new());
    let mut warnings = Vec::new();
    let server = generate_server(&input, &mut warnings).expect("server emitted");
    assert!(server.contains("pub const ChatHandlers = struct {"));
    // Bidirectional handler is fire-and-forget; unidirectional has a response out.
    assert!(
        server.contains(
            "say: *const fn (ctx: *anyopaque, msg: *const types.SayMessage) anyerror!void,"
        )
    );
    assert!(server.contains("ping: *const fn (ctx: *anyopaque, resp: *types.Pong) anyerror!void,"));
    assert!(server.contains("pub const chat_service_wire_id: u64 = 7;"));
    assert!(server.contains("pub const chat_op_say_wire_id: u64 = 0;"));
    // Verbose + compact router twins.
    assert!(server.contains("pub fn route_chat_channel("));
    assert!(server.contains("pub fn route_chat_channel_compact("));
    assert!(server.contains("std.mem.eql(u8, method, \"Say\")"));
    assert!(server.contains("        0 => {"));
}

