#[test]
fn text_literal_choice_is_an_enum_with_wire_names() {
    let rule = CsilRule {
        name: "Color".to_string(),
        rule_type: CsilRuleType::TypeChoice(vec![
            CsilTypeExpression::Literal(CsilLiteralValue::Text("red".to_string())),
            CsilTypeExpression::Literal(CsilLiteralValue::Text("dark-green".to_string())),
        ]),
        position: pos(),
        doc_comments: vec![],
    };
    let input = input_with_rules(vec![rule], "zig", HashMap::new());
    let config = ZigConfig::from_options(&input.config.options).unwrap();
    let types = generate_types(&input, &config).unwrap();
    assert!(types.contains("pub const Color = enum {"));
    assert!(types.contains("    red,"));
    // kebab literal -> snake_case Zig tag, but the wire form stays verbatim.
    assert!(types.contains("    dark_green,"));
    assert!(types.contains(".dark_green => \"dark-green\","));
    assert!(types.contains("pub fn wire_name(self: Color) []const u8"));
}

