#[test]
fn types_emitted_in_by_value_dependency_order() {
    // Outer embeds Inner by value, but is declared first; the topo sort must emit
    // Inner before Outer so a by-value member's type is seen first.
    let outer = group_rule(
        "Outer",
        vec![bare_entry(
            "inner",
            CsilTypeExpression::Reference("Inner".to_string()),
        )],
    );
    let inner = group_rule("Inner", vec![bare_entry("n", builtin("int"))]);
    let input = input_with_rules(vec![outer, inner], "zig", HashMap::new());
    let config = ZigConfig::from_options(&input.config.options).unwrap();
    let types = generate_types(&input, &config).unwrap();
    let inner_at = types.find("pub const Inner = struct").unwrap();
    let outer_at = types.find("pub const Outer = struct").unwrap();
    assert!(
        inner_at < outer_at,
        "Inner must be emitted before Outer:\n{types}"
    );
}

#[test]
